declare const browser: typeof chrome | undefined;

// Firefox documents its `chrome` namespace as callback-only; `browser` is its promise API.
export const getExtensionApi = (): typeof chrome | undefined => {
  if (typeof browser !== "undefined") return browser;
  if (typeof chrome !== "undefined") return chrome;
  return undefined;
};
